"""``registry/plugins/registry.json`` — the discovery index's per-plugin ``commands[]``.

The index is generated by ``scripts/gen_plugin_registry.py`` (the gate step "plugin
registry index — matches the manifests" re-derives it from the manifests and fails on
drift), but nothing pinned what the column *means*. For ``mini`` it was silently empty,
so the index read "navig-mini adds nothing to navig" while ``navig mini status`` was
right there on the command line.

``commands[]`` holds the bare top-level ``navig <verb>`` names a plugin's surface adds —
the shape every populated neighbour uses (``mobile`` → ``["android", "ios", "mobile"]``,
``antivirus`` → ``["antivirus"]``, ``cabinet`` → ``["cabinet", "paperwork"]``). The
second test below pins that shape for the whole file, so a future entry cannot smuggle a
full command path or a console-script name into it.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

# Spelled as ONE segment — the plugin-subject detector in
# tests/quality/test_source_guards_are_wired.py reads `<root> / "plugins"` as "this guard
# scans the plugin source tree", which this does not: it reads one index file. Same spelling
# test_bay_catalog_artifact.py uses for the same file.
REGISTRY = Path(__file__).resolve().parents[3] / "registry/plugins/registry.json"


@pytest.fixture(scope="module")
def entries() -> list[dict]:
    if not REGISTRY.is_file():
        pytest.skip(f"plugin registry index not in this checkout: {REGISTRY}")
    return json.loads(REGISTRY.read_text(encoding="utf-8"))["plugins"]


def _entry(entries: list[dict], plugin_id: str) -> dict:
    found = [e for e in entries if e.get("id") == plugin_id]
    assert len(found) == 1, f"expected exactly one {plugin_id!r} entry, found {len(found)}"
    return found[0]


def test_mini_lists_the_navig_verbs_it_mounts(entries: list[dict]) -> None:
    """`navig mini status|run|deploy|logs|restart|list` is this plugin's navig surface.

    Mirrors the neighbouring entries' convention (bare verbs, one per string). The verb
    is mounted by the builtin plugin app at ``core/navig/builtins/mini_control``, not by
    an entry point in the pip package, which is why ``scripts/gen_plugin_registry.py``
    carries it in ``CORE_PROVIDED_VERBS`` instead of reading it off the manifest.
    """
    assert _entry(entries, "mini")["commands"] == ["mini"]


def test_commands_are_bare_navig_verb_names(entries: list[dict]) -> None:
    """`commands` is what the Bay and the docs print as `navig <verb>`.

    A full path (``navig mini status``) or a console script (``navig-mini``) would render
    as a command nobody can type after ``navig``; the ``scripts`` column already exists
    for console scripts.
    """
    malformed = {
        e["id"]: e["commands"]
        for e in entries
        if not isinstance(e.get("commands"), list)
        or any(
            not isinstance(v, str) or not v or " " in v or v.startswith("navig")
            for v in e["commands"]
        )
    }
    assert not malformed, f"registry commands[] entries that are not bare verbs: {malformed}"


def test_blackbox_lists_the_navig_verbs_core_mounts(entries: list[dict]) -> None:
    """`navig blackbox` / `navig bb` come from core's _EXTERNAL_CMD_MAP, so the
    generator must supply them (CORE_PROVIDED_VERBS) or the index claims the
    plugin adds nothing to navig — the exact defect mini just fixed.
    """
    assert _entry(entries, "blackbox")["commands"] == ["bb", "blackbox"]
