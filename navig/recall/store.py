    def record_session_links(self, record_ids: Iterable[str]) -> dict[str, dict[str, Any]]:
        """Record id → what its evidence SESSIONS did: ``{"committed": [commit:<sha>…],
        "touched": [file keys…]}``. Batched; missing records map to empty dicts.
        This is the session→commit edge of PROJECT → SESSION → FILE → COMMIT for a record."""
        ids = list(dict.fromkeys(record_ids))
        out: dict[str, dict[str, Any]] = {i: {"committed": [], "touched": []} for i in ids}
        for i in range(0, len(ids), 500):
            chunk = ids[i:i + 500]
            marks = ", ".join("?" for _ in chunk)
            rows = self._read_all(
                f"SELECT DISTINCT e.record_id, l.rel, l.b FROM evidence e "
                f"JOIN links l ON l.a = e.source_id AND l.rel IN ('committed', 'touched') "
                f"WHERE e.record_id IN ({marks})",
                tuple(chunk),
            )
            for rid, rel, b in rows:
                out.setdefault(rid, {"committed": [], "touched": []})[rel].append(b)
        return out

