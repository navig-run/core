def _source_dict(row: sqlite3.Row) -> dict[str, Any]:
    d = dict(row)
    try:
        d["meta"] = json.loads(d.pop("meta_json") or "{}")
    except (TypeError, ValueError):
        d["meta"] = {}
    return d


def _record_from_row(row: sqlite3.Row) -> Record:
    d = dict(row)
    return Record(
        id=d["id"], type=d["type"], title=d["title"], summary=d["summary"], body=d["body"],
        project=d["project"], status=d["status"], status_basis=d["status_basis"],
        endorsement=d["endorsement"], impl=d["impl"], confidence=float(d["confidence"]),
        canonical_key=d["canonical_key"], aliases=json.loads(d["aliases_json"] or "[]"),
        tags=json.loads(d["tags_json"] or "[]"), created=d["created"], updated=d["updated"],
        ext_id=d["ext_id"], attrs=json.loads(d["attrs_json"] or "{}"),
        lifecycle=d.get("lifecycle", "unknown"),
    )


_store: RecallStore | None = None


def get_recall_store() -> RecallStore:
    """Process-wide store for the current ``data_dir()`` (re-checked so tests can relocate it)."""
    global _store
    from navig.recall.paths import index_db  # noqa: PLC0415

    want = index_db()
    if _store is None or _store.db_path != want:
        _store = RecallStore(want)
    return _store
