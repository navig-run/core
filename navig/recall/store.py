    def search_records(self, query: str, *, project: str | None = None, rtype: str | None = None,
                       status: str | None = None, limit: int = 20, any_term: bool = False,
                       projects: Iterable[str] | None = None) -> list[dict[str, Any]]:
        q = match_query(query, any_term=any_term)
        if not q:
            return []
        where: list[str] = []
        args: list[Any] = []
        for col, val in (("r.type", rtype), ("r.status", status)):
            if val:
                where.append(f"{col} = ?")
                args.append(val)
        clause, pargs = _project_clause("r.project", project, projects)
        if clause:
            where.append(clause)
            args.extend(pargs)
        extra = (" AND " + " AND ".join(where)) if where else ""
        if self.has_fts():
            sql = (
                "SELECT r.id, r.type, r.title, r.project, r.status, r.status_basis, r.impl, r.updated, "
                "snippet(records_fts, 2, '[', ']', '…', 16) AS snip FROM records_fts f "
                f"JOIN records r ON r.id = f.rid WHERE records_fts MATCH ?{extra} "
                "ORDER BY bm25(records_fts, 10.0, 6.0, 3.0, 1.0) LIMIT ?"
            )
            params = (q, *args, limit)
        else:
            like = "%" + query.strip() + "%"
            sql = (
                "SELECT r.id, r.type, r.title, r.project, r.status, r.status_basis, r.impl, r.updated, "
                "substr(r.summary, 1, 200) AS snip FROM records r "
                f"WHERE (r.title LIKE ? OR r.summary LIKE ? OR r.body LIKE ?){extra} ORDER BY r.updated DESC LIMIT ?"
            )
            params = (like, like, like, *args, limit)
        try:
            return [dict(r) for r in self._read_all(sql, params)]
        except sqlite3.OperationalError as exc:
            logger.debug("recall record search failed: %s", exc)
            return []

    # ── Links & events ────────────────────────────────────────

    def add_links(self, links: Iterable[tuple[str, str, str]]) -> list[tuple[str, str, str]]:
        """Insert links; returns the ones that were new. A (pair, rel) the operator unlinked is
        skipped — derivation never re-creates a link the person removed."""
        rows = list(links)
        if not rows:
            return []

        def _ins(conn: sqlite3.Connection) -> list[tuple[str, str, str]]:
            fresh = []
            for r in rows:
                a, b, rel = r
                if self._tombstone_row(conn, a, b, rel):
                    continue
                if conn.execute("INSERT OR IGNORE INTO links (a, b, rel) VALUES (?, ?, ?)", r).rowcount:
                    fresh.append(r)
            return fresh

        return self._tx(_ins)

    def apply_links(self, links: Iterable[tuple[str, str, str]]) -> int:
        """Replay links in order: ``(a, b, rel)`` inserts, a tombstone ``(a, b, "-rel")`` removes
        that link (an unlink). Returns the number of links present afterwards from this replay."""
        rows = list(links)

        def _replay(conn: sqlite3.Connection) -> int:
            n = 0
            for a, b, rel in rows:
                if rel.startswith("-"):
                    real = rel[1:]
                    n -= conn.execute("DELETE FROM links WHERE a = ? AND b = ? AND rel = ?", (a, b, real)).rowcount
                    conn.execute("INSERT OR IGNORE INTO link_tombstones (a, b, rel) VALUES (?, ?, ?)",
                                 (a, b, real))
                else:
                    # Vault order is the truth: a link written after an unlink clears its
                    # tombstone; a link written before it never outlives it.
                    conn.execute("DELETE FROM link_tombstones WHERE a = ? AND b = ? AND rel = ?",
                                 (a, b, rel))
                    n += conn.execute("INSERT OR IGNORE INTO links (a, b, rel) VALUES (?, ?, ?)", (a, b, rel)).rowcount
            return n

        return self._tx(_replay) if rows else 0

    def unlink(self, a: str, b: str, rels: Iterable[str]) -> list[tuple[str, str, str]]:
        """Remove links between *a* and *b*; returns the tombstones to append to the vault —
        one per link actually removed, so the vault and the index agree after `reindex` and
        the caller reports the real count ("Nothing was linked" stays honest)."""
        removed: list[tuple[str, str, str]] = []
        for rel in rels:
            if self.apply_links([(a, b, f"-{rel}")]):
                removed.append((a, b, f"-{rel}"))
        return removed

    def sessions_for(self, key: str | None = None, *, project: str | None = None,
                     limit: int = 200) -> list[tuple[dict[str, Any], list[str]]]:
        """Claude Code sessions linked to a target key (``file:…`` / ``plan:…`` / ``commit:…``),
        or every session of *project* when no key is given. Newest activity first.
        A short commit id matches any longer id with that prefix (and vice versa)."""
        if key is None:
            srcs = self.list_sources(adapter="claude_code", project=project)[:limit]
            return [(s, []) for s in srcs]
        if key.startswith("commit:"):
            # Indexed lookup (GLOB uses idx_links_b; a LIKE/OR mix SCANs the table —
            # measured 0.01 ms vs 10.8 ms at 50k rows): the 7-char sha prefix pulls every
            # candidate, then the full given prefix is checked BOTH ways in Python, so a
            # 7-char id matches a longer stored id and vice versa without a scan.
            sha = key[len("commit:"):]
            rows = [r for r in self._read_all(
                "SELECT a, rel, b FROM links WHERE b GLOB ? AND a LIKE 'cc:%'",
                (f"commit:{sha[:7]}*",),
            ) if r["b"].startswith(key) or key.startswith(r["b"])]
        else:
            rows = self._read_all("SELECT a, rel FROM links WHERE b = ? AND a LIKE 'cc:%'", (key,))
        rels: dict[str, list[str]] = {}
        for r in rows:
            rels.setdefault(r["a"], []).append(r["rel"])
        out: list[tuple[dict[str, Any], list[str]]] = []
        for sid, rs in rels.items():
            src = self.get_source(sid)
            if src is None or (project and src.get("project") != project):
                continue
            out.append((src, rs))
        out.sort(key=lambda t: t[0].get("last_ts") or "", reverse=True)
        return out[:limit]

    def replace_derived_links(self, a: str, links: Iterable[tuple[str, str, str]],
                              rels: Iterable[str]) -> list[tuple[str, str, str]]:
        """Make *a*'s links with relations in *rels* exactly *links*. Returns the changes as
        vault lines: new links, and a tombstone ``-rel`` for each one no longer derived."""
        want = {(x, b, r) for x, b, r in links if x == a}
        rels = tuple(rels)
        have = {(a, lk["b"], lk["rel"]) for lk in self.links_of(a) if lk["rel"] in rels}
        # The person's unlink outranks the derivation: a tombstoned (pair, rel) is never wanted
        # again. It stays out of `want`, so a legacy row that predates the tombstone lands in
        # `have - want` and is retired — once, because the row is gone afterwards.
        want = {w for w in want if not self.link_tombstoned(*w)}
        changes = [(x, b, f"-{r}") for x, b, r in sorted(have - want)] + sorted(want - have)
        self.apply_links(changes)
        return changes

    @staticmethod
    def _tombstone_row(conn: sqlite3.Connection, a: str, b: str, rel: str) -> Any:
        return conn.execute("SELECT 1 FROM link_tombstones WHERE a = ? AND b = ? AND rel = ?",
                            (a, b, rel)).fetchone()

    def link_tombstoned(self, a: str, b: str, rel: str) -> bool:
        """True when the operator removed this (a, b, rel) — derivation must not restore it."""
        return self._read_one("SELECT 1 FROM link_tombstones WHERE a = ? AND b = ? AND rel = ?",
                              (a, b, rel)) is not None

    def clear_tombstone(self, a: str, b: str, rel: str) -> None:
        """Forget one unlink — an explicit manual link (never a derivation) may re-open it."""
        self._write("DELETE FROM link_tombstones WHERE a = ? AND b = ? AND rel = ?", (a, b, rel))

    def links_of(self, a: str) -> list[dict[str, Any]]:
        return [dict(r) for r in self._read_all("SELECT b, rel FROM links WHERE a = ? ORDER BY rel, b", (a,))]

    def related(self, record_id: str) -> list[dict[str, Any]]:
        rows = self._read_all(
            "SELECT l.rel, l.b AS other, 'out' AS dir, r.title, r.type FROM links l LEFT JOIN records r ON r.id = l.b "
            "WHERE l.a = ? UNION ALL "
            "SELECT l.rel, l.a AS other, 'in' AS dir, r.title, r.type FROM links l LEFT JOIN records r ON r.id = l.a "
            "WHERE l.b = ?",
            (record_id, record_id),
        )
        return [dict(r) for r in rows]

    def add_events(self, events: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
        """Insert events; returns the ones that were new (ids are content-derived)."""
