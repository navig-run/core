    def upsert_commits(self, rows: Iterable[dict[str, Any]]) -> int:
        """Upsert git observations (metadata only). Returns the number of rows written."""
        items = [r for r in rows if r.get("sha")]
        if not items:
            return 0

        def _up(conn: sqlite3.Connection) -> int:
            for r in items:
                conn.execute(
                    "INSERT INTO commits (sha, project, subject, author, author_ts, committer_ts, branch, "
                    "files_json, merged, git_root, observed_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) "
                    "ON CONFLICT(sha) DO UPDATE SET project=excluded.project, subject=excluded.subject, "
                    "author=excluded.author, author_ts=excluded.author_ts, "
                    "committer_ts=excluded.committer_ts, branch=excluded.branch, "
                    "files_json=excluded.files_json, merged=excluded.merged, "
                    "git_root=excluded.git_root, observed_at=excluded.observed_at",
                    (r["sha"], r.get("project", "shared"), r.get("subject", ""), r.get("author", ""),
                     r.get("author_ts", ""), r.get("committer_ts", ""), r.get("branch", ""),
                     json.dumps(r.get("files") or [], ensure_ascii=False), r.get("merged", "unknown"),
                     r.get("git_root", ""), r.get("observed_at", "")),
                )
            return len(items)
        return int(self._tx(_up))

