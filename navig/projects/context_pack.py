"""The context pack — the best single description of a project, on a budget.

One builder, many consumers: the OS hub's Context tab, the agent's prompt (via
``agent/conv``), ``navig project context --json`` for Claude Code and other
tools, and the AI analyst's input. How it is built:

* **Ordered sources with per-source budgets + a report** of raw vs injected
  size, truncation and pressure — so "why does the agent not know X" has an
  answer you can read, not guess.
* **Plan files in priority order** (the order Forge's plan reader uses).
* **Agent instruction files, root first then nested by depth**, so a monorepo's
  package-level rules are seen after the repository's own.
* **Tree + symbols outline**: a gitignore-aware tree with top-level symbols of
  the entry-point files — Python via ``ast``, JS/TS, Rust and Go via anchored
  regexes, so no tree-sitter dependency.
* **Rebuild only when the inputs changed**: a fingerprint over every source's
  mtime+size and git HEAD gates the rebuild.

Truncation keeps the head AND the tail of a long doc: plan logs grow at the
end, so a head-only cut drops exactly the newest state.
"""

from __future__ import annotations

import ast
import hashlib
import logging
import os
import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from navig.projects import docs as _docs
from navig.projects import todos as _todos

logger = logging.getLogger(__name__)

__all__ = ["PIN_FILE", "SOURCE_BUDGETS", "TOTAL_BUDGET", "build_pack", "pin_pack", "render_outline"]

#: (source id, label, char budget) in injection order.
SOURCE_BUDGETS: tuple[tuple[str, str, int], ...] = (
    ("identity", "Identity", 3000),
    ("plans", "Plans", 14000),
    ("todos", "Open todos", 3000),
    ("agent", "Agent instructions", 6000),
    ("readme", "README", 2500),
    ("profile", "Stack & scripts", 2500),
    ("outline", "Code outline", 5000),
    ("git", "Git", 1000),
    ("brief", "Latest AI brief", 2000),
    ("chats", "Shared AI conversations", 3000),
)
TOTAL_BUDGET = 36000
PRESSURE = 0.85
PIN_FILE = ".navig/context.pack.md"
_PIN_MARKER = "<!-- generated by navig: project context pack -->"
_PER_PLAN_BUDGET = 4000
_PLAN_STEMS = ("VISION", "ROADMAP", "CURRENT_PHASE", "DEV_PLAN", "TASKS", "SPEC")
_IDENTITY_FILES = (".navig/context.md", ".navig/ai_system_prompt.txt", ".navig/GENESIS.md")
_OUTLINE_MAX_FILES = 5000
_SYMBOL_FILES = 24
_SYMBOLS_PER_FILE = 12
_SKIP_DIRS = {"node_modules", ".git", "dist", "build", "out", ".next", "target", ".dev", ".venv",
              "venv", "__pycache__", ".turbo", ".cache", "coverage", ".lab", ".navig"}
_ENTRY_STEMS = {"main", "index", "app", "server", "cli", "__main__", "lib", "mod", "plugin", "worker"}
_CODE_EXTS = {".py", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".rs", ".go"}

_TS_SYM = re.compile(
    r"^export\s+(?:default\s+)?(?:declare\s+)?(?:async\s+)?"
    r"(function\*?|class|const|let|interface|type|enum)\s+([A-Za-z_$][\w$]*)", re.M)
_RS_SYM = re.compile(r"^pub\s+(?:async\s+)?(fn|struct|enum|trait|mod)\s+([A-Za-z_]\w*)", re.M)
_GO_SYM = re.compile(r"^func\s+(?:\([^)]*\)\s*)?([A-Z]\w*)", re.M)


# ── helpers ─────────────────────────────────────────────────────────────────


def _read(path: Path, limit: int = 512 * 1024) -> str:
    try:
        with path.open("r", encoding="utf-8", errors="replace") as fh:
            return fh.read(limit)
    except OSError:
        return ""


def _truncate(text: str, budget: int) -> tuple[str, bool]:
    """Fit *text* into *budget* chars, keeping head (70%) and tail (30%)."""
    if len(text) <= budget:
        return text, False
    marker = "\n\n… [{n} chars omitted] …\n\n"
    room = max(budget - len(marker) - 8, 40)
    head = int(room * 0.7)
    tail = room - head
    omitted = len(text) - head - tail
    return text[:head].rstrip() + marker.format(n=omitted) + text[-tail:].lstrip(), True


def _stat_sig(path: Path) -> str:
    try:
        st = path.stat()
        return f"{path.name}:{st.st_size}:{int(st.st_mtime)}"
    except OSError:
        return f"{path.name}:-"


# ── outline (tree + symbols) ────────────────────────────────────────────────


def _list_files(root: Path) -> list[str]:
    """Posix relative paths of the project's files, gitignore-aware when possible."""
    from navig.projects.gitinfo import has_own_repo  # noqa: PLC0415

    if has_own_repo(root):
        try:
            cp = subprocess.run(
                ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
                cwd=str(root), capture_output=True, text=True, encoding="utf-8", errors="replace",
                timeout=5, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
            )
            if cp.returncode == 0:
                files = [ln for ln in cp.stdout.splitlines() if ln and not any(
                    p in _SKIP_DIRS for p in ln.split("/")[:-1])]
                return files[:_OUTLINE_MAX_FILES]
        except (OSError, subprocess.SubprocessError):
            logger.debug("git ls-files failed for %s", root, exc_info=True)
    out: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in _SKIP_DIRS and not d.startswith("."))
        rel_dir = Path(dirpath).relative_to(root).as_posix()
        for fn in sorted(filenames):
            out.append(fn if rel_dir == "." else f"{rel_dir}/{fn}")
            if len(out) >= _OUTLINE_MAX_FILES:
                return out
    return out


def _symbols(path: Path) -> list[str]:
    text = _read(path, 256 * 1024)
    if not text:
        return []
    ext = path.suffix.lower()
    names: list[str] = []
    if ext == ".py":
        try:
            tree = ast.parse(text)
        except (SyntaxError, ValueError):
            return []
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                names.append(f"class {node.name}")
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
                names.append(f"def {node.name}")
    elif ext in (".ts", ".tsx", ".js", ".jsx", ".mjs"):
        names = [f"{k.rstrip('*')} {n}" for k, n in _TS_SYM.findall(text)]
    elif ext == ".rs":
        names = [f"{k} {n}" for k, n in _RS_SYM.findall(text)]
    elif ext == ".go":
        names = [f"func {n}" for n in _GO_SYM.findall(text)]
    return names[:_SYMBOLS_PER_FILE]


def render_outline(root: Path, files: list[str] | None = None) -> str:
    """A two-level directory tree with file counts, then symbols of entry files."""
    files = files if files is not None else _list_files(root)
    if not files:
        return ""
    top_files: list[str] = []
    dirs: dict[str, dict[str, int]] = {}
    totals: dict[str, int] = {}
    for f in files:
        parts = f.split("/")
        if len(parts) == 1:
            top_files.append(f)
            continue
        totals[parts[0]] = totals.get(parts[0], 0) + 1
        sub = dirs.setdefault(parts[0], {})
        if len(parts) > 2:
            sub[parts[1]] = sub.get(parts[1], 0) + 1
    lines = [f"{len(files)} files"]
    for d in sorted(dirs, key=str.lower):
        lines.append(f"{d}/ ({totals[d]})")
        subs = sorted(dirs[d].items(), key=lambda kv: (-kv[1], kv[0].lower()))[:8]
        lines += [f"  {s}/ ({n})" for s, n in subs]
        if len(dirs[d]) > 8:
            lines.append(f"  … {len(dirs[d]) - 8} more dirs")
    lines += sorted(top_files, key=str.lower)[:30]

    def _entry_rank(f: str) -> tuple:
        p = Path(f)
        return (0 if p.stem.lower() in _ENTRY_STEMS else 1, f.count("/"), f.lower())

    code = sorted((f for f in files if Path(f).suffix.lower() in _CODE_EXTS
                   and ".test." not in f and "/tests/" not in f and not f.startswith("tests/")),
                  key=_entry_rank)
    sym_lines: list[str] = []
    for f in code:
        if len(sym_lines) >= _SYMBOL_FILES:
            break
        syms = _symbols(root / f)
        if syms:
            sym_lines.append(f"{f}: " + ", ".join(syms))
    if sym_lines:
        lines += ["", "Key symbols:"] + sym_lines
    return "\n".join(lines)


# ── sources ─────────────────────────────────────────────────────────────────


def _collect_sources(root: Path, name: str, manifest: dict[str, Any], profile: dict[str, Any],
                     git: dict[str, Any], brief: str, doc_index: list[dict[str, Any]],
                     todos: list[dict[str, Any]]) -> tuple[dict[str, tuple[str, list[str]]], list[Path]]:
    """source id → (raw text, files used), plus every file path the pack depends on."""
    used: list[Path] = []
    out: dict[str, tuple[str, list[str]]] = {}

    # identity
    parts: list[str] = []
    files: list[str] = []
    desc = str(manifest.get("description") or "").strip()
    if desc:
        parts.append(desc)
    for rel in _IDENTITY_FILES:
        p = root / rel
        if p.is_file():
            parts.append(f"### {rel}\n{_read(p).strip()}")
            files.append(rel)
            used.append(p)
    out["identity"] = ("\n\n".join(parts), files)

    # plans — canonical docs in priority order, each individually budgeted
    plan_docs = [d for d in doc_index if d.get("group") == "plans" and d.get("canonical") is not None]
    by_stem: dict[str, dict[str, Any]] = {}
    for d in plan_docs:
        stem = Path(d["path"]).stem.upper()
        by_stem.setdefault(stem, d)  # index is sorted shallow-first, so the nearest copy wins
    parts, files = [], []
    for stem in _PLAN_STEMS:
        d = by_stem.get(stem)
        if not d:
            continue
        p = root / d["path"]
        body, _cut = _truncate(_read(p).strip(), _PER_PLAN_BUDGET)
        parts.append(f"### {d['path']}\n{body}")
        files.append(d["path"])
        used.append(p)
    extra = [d for d in doc_index if d.get("group") in ("plans", "tasks", "briefs")
             and d["path"] not in files][:40]
    if extra:
        parts.append("Other plan docs: " + ", ".join(d["path"] for d in extra))
        used += [root / d["path"] for d in extra]
    try:
        from navig.projects.ideas import list_ideas  # noqa: PLC0415

        idea_state = list_ideas(root)
        c = idea_state["counts"]
        if idea_state["ideas"]:
            parts.append(f"Ideas (not planned yet, {idea_state['path']}): {c['inbox']} new · "
                         f"{c['exploring']} exploring · {c['parked']} parked · {c['promoted']} promoted")
            used.append(root / idea_state["path"])
    except Exception:  # noqa: BLE001 — the ideas line is a convenience in the pack
        logger.debug("ideas summary failed for %s", root, exc_info=True)
    out["plans"] = ("\n\n".join(parts), files)

    # todos
    open_todos = [t for t in todos if t["state"] != "done"]
    counts = _todos.summarize(todos)
    lines = [f"{counts['open']} open · {counts['in_progress']} in progress · {counts['done']} done"]
    for t in sorted(open_todos, key=lambda t: 0 if t["state"] == "in_progress" else 1)[:60]:
        mark = "[~]" if t["state"] == "in_progress" else "[ ]"
        where = f" ({t['heading']})" if t.get("heading") else ""
        lines.append(f"- {mark} {t['text']}{where} — {t['path']}")
    out["todos"] = ("\n".join(lines) if todos else "", sorted({t["path"] for t in open_todos}))

    # agent instruction files: root first, then nested (depth ≤ 2), max 6
    agent_files: list[Path] = []
    for fn in ("AGENTS.md", "CLAUDE.md", ".claude/CLAUDE.md", ".github/copilot-instructions.md", "GEMINI.md"):
        p = root / fn
        if p.is_file():
            agent_files.append(p)
    try:
        for sub in sorted(root.iterdir()):
            if len(agent_files) >= 6 or not sub.is_dir() or sub.name in _SKIP_DIRS or sub.name.startswith("."):
                continue
            for fn in ("AGENTS.md", "CLAUDE.md"):
                if (sub / fn).is_file() and len(agent_files) < 6:
                    agent_files.append(sub / fn)
    except OSError:
        pass
    per = max(800, 6000 // max(1, len(agent_files)))
    parts = []
    for p in agent_files:
        body, _cut = _truncate(_read(p).strip(), per)
        parts.append(f"### {p.relative_to(root).as_posix()}\n{body}")
        used.append(p)
    out["agent"] = ("\n\n".join(parts), [p.relative_to(root).as_posix() for p in agent_files])

    # readme
    readme = (profile.get("readme_excerpt") or "").strip()
    out["readme"] = (readme, ["README.md"] if readme else [])
    if (root / "README.md").is_file():
        used.append(root / "README.md")

    # profile
    scripts = profile.get("scripts", [])
    lines = []
    if profile.get("stack"):
        lines.append("Stack: " + ", ".join(profile["stack"]))
    if profile.get("package_manager"):
        lines.append(f"Package manager: {profile['package_manager']}")
    if profile.get("packages"):
        lines.append("Workspace packages: " + ", ".join(
            f"{p['name']} ({p['cwd']})" for p in profile["packages"][:30]))
    if scripts:
        def _fmt(s: dict[str, Any]) -> str:
            tag = " [long-running]" if s.get("long_running") else ""
            tag += " [danger]" if s.get("danger") else ""
            where = f"{s['cwd']}: " if s.get("cwd") else ""
            return f"- {where}{s['run'] or s['name']}{tag}"
        lines.append(f"Scripts ({len(scripts)}):")
        lines += [_fmt(s) for s in scripts[:80]]
    out["profile"] = ("\n".join(lines), [m for m in ("package.json", "pyproject.toml", "Makefile", "justfile",
                                                      "pnpm-workspace.yaml") if (root / m).is_file()])
    used += [root / m for m in out["profile"][1]]

    # outline
    try:
        out["outline"] = (render_outline(root), [])
    except Exception:  # noqa: BLE001 — an outline failure only costs the outline
        logger.debug("outline failed for %s", root, exc_info=True)
        out["outline"] = ("", [])

    # git
    if git.get("unknown"):
        out["git"] = ("Git state unknown (git did not answer in time).", [])
    elif git.get("repo"):
        lines = [f"Branch: {git.get('branch')} · {git.get('dirty', 0)} uncommitted change(s)"]
        lines += [f"- {c['sha']} {c['subject']} ({c['date'][:10]})" for c in git.get("recent", [])]
        out["git"] = ("\n".join(lines), [])
    else:
        out["git"] = ("", [])

    out["brief"] = (brief.strip(), [])
    return out, used


def _shared_chats(root: Path, name: str) -> tuple[str, str]:
    """Decisions and open items from chats the person shared at the ``agent`` level AND mapped
    to this project (a NAVIG folder's ``brain_project``). ``local`` shares never enter here: the
    pack is sent to the AI provider. Returns ``(markdown, signature)``; empty without the
    chat library plugin."""
    try:
        from navig_chats.deck_routes import get_store  # noqa: PLC0415
        from navig_chats.handoff import PACK_MARKER, build_handoff  # noqa: PLC0415
        from navig_chats.store import brain_shared  # noqa: PLC0415
    except ImportError:
        return "", ""
    try:
        keys = {k.casefold() for k in (name, root.name, str(root)) if k}
        rows = [r for r in brain_shared(get_store(), min_level="agent")
                if (r.get("brain_project") or "").casefold() in keys]
        if not rows:
            return "", ""
        sig = ";".join(f"{r['id']}@{r.get('revision')}" for r in rows)
        pack = build_handoff(get_store(), [r["id"] for r in rows], title=name, compact=True)
        body = pack["markdown"].replace(PACK_MARKER, "").strip()
        body = body.split("\n", 1)[1].strip() if body.startswith("# ") else body  # the pack's own H1
        return body.replace("\n## ", "\n### "), hashlib.sha256(sig.encode()).hexdigest()[:12]
    except Exception:  # noqa: BLE001 — shared chats are an extra; never break the pack
        logger.debug("shared chats skipped for %s", root, exc_info=True)
        return "", ""


def _fingerprint(root: Path, used: list[Path], head: str, brief_id: str) -> str:
    h = hashlib.sha256()
    h.update(str(root).encode("utf-8", "replace"))
    for p in sorted({str(u) for u in used}):
        h.update(_stat_sig(Path(p)).encode("utf-8", "replace"))
    h.update(head.encode())
    h.update(brief_id.encode())
    return h.hexdigest()[:20]


def _latest_brief(store: Any, root: Path) -> tuple[str, str]:
    if store is None:
        return "", ""
    try:
        for a in store.list_analyses(root, kind="brief", limit=5):
            if a.get("status") == "accepted" or a.get("status") == "proposed":
                return str((a.get("output") or {}).get("markdown") or ""), a["id"]
    except Exception:  # noqa: BLE001
        logger.debug("brief lookup failed", exc_info=True)
    return "", ""


def build_pack(
    root: Path, *, name: str = "", manifest: dict[str, Any] | None = None,
    profile: dict[str, Any] | None = None, git: dict[str, Any] | None = None,
    store: Any = None, force: bool = False,
) -> dict[str, Any]:
    """Build (or return the cached) context pack for *root*."""
    from navig.projects import gitinfo  # noqa: PLC0415
    from navig.projects.profile import build_profile  # noqa: PLC0415

    root = Path(root)
    doc_index = _docs.index_docs(root)
    profile = profile if profile is not None else build_profile(root)
    git = git if git is not None else gitinfo.git_state(root)
    todos = _todos.extract_todos(root, doc_index)
    brief, brief_id = _latest_brief(store, root)
    sources, used = _collect_sources(root, name or root.name, manifest or {}, profile, git, brief,
                                     doc_index, todos)
    chats_md, chats_sig = _shared_chats(root, name or root.name)
    sources["chats"] = (chats_md, [])
    fp = _fingerprint(root, used + [root / d["path"] for d in doc_index], gitinfo.head_sha(root),
                      f"{brief_id}|{chats_sig}")

    if store is not None and not force:
        try:
            cached = store.get_context(root)
            if cached and cached.get("fingerprint") == fp:
                return {**cached["pack"], "cached": True}
        except Exception:  # noqa: BLE001
            logger.debug("context cache read failed", exc_info=True)

    sections: list[dict[str, Any]] = []
    report: list[dict[str, Any]] = []
    total = 0
    for sid, label, budget in SOURCE_BUDGETS:
        raw, files = sources.get(sid, ("", []))
        room = max(0, min(budget, TOTAL_BUDGET - total))
        body, cut = _truncate(raw, room) if raw else ("", False)
        if room == 0 and raw:
            body, cut = "", True
        total += len(body)
        report.append({
            "source": sid, "label": label, "budget": budget, "files": files,
            "raw_chars": len(raw), "injected_chars": len(body), "truncated": cut,
            "pressure": round(len(body) / budget, 3) if budget else 0.0,
            "warn": bool(budget) and len(body) / budget >= PRESSURE,
        })
        if body:
            sections.append({"source": sid, "label": label, "content": body})

    title = name or root.name
    md = [f"# Project context — {title}", f"_{root}_", ""]
    for s in sections:
        md += [f"## {s['label']}", s["content"], ""]
    pack = {
        "fingerprint": fp,
        "built_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "name": title,
        "path": str(root),
        "markdown": "\n".join(md).rstrip() + "\n",
        "sections": sections,
        "report": {
            "total_budget": TOTAL_BUDGET,
            "total_injected": total,
            "total_raw": sum(r["raw_chars"] for r in report),
            "approx_tokens": total // 4,
            "sources": report,
        },
        "todo_counts": _todos.summarize(todos),
        "cached": False,
    }
    if store is not None:
        try:
            store.put_context(root, fp, pack)
        except Exception:  # noqa: BLE001 — the cache is an optimisation
            logger.debug("context cache write failed", exc_info=True)
    return pack


def pin_pack(root: Path, pack: dict[str, Any]) -> dict[str, Any]:
    """Write the pack to ``.navig/context.pack.md`` so other agents can read it.

    Refuses to overwrite a file it did not write: a hand-authored doc at that
    path is the operator's, not ours.
    """
    from navig.projects import textio  # noqa: PLC0415

    target = root / PIN_FILE
    if target.is_file():
        head = _read(target, 4096)
        if _PIN_MARKER not in head:
            raise _docs.DocError(f"{PIN_FILE} exists and was not written by navig — not overwriting", 409)
    body = f"{_PIN_MARKER}\n<!-- regenerate: navig project context --pin -->\n\n{pack['markdown']}"
    textio.write_exact(target, body)
    return {"path": PIN_FILE, "chars": len(body)}
