"""
navig.commands.mount — Universal Drive Mounting (Windows NTFS junctions).

Commands
--------
  navig mount add     <label> <source> [target]  — register and create junction
  navig mount list                                — list all registered mounts
  navig mount remove  <label>                     — delete junction + registry entry
  navig mount verify                              — check all junctions are alive
  navig mount sync                                — verify + regenerate mount-drive.ps1

Registry
--------
  %USERPROFILE%\\.navig\\registry\\drives.json

Helper script
-------------
  %USERPROFILE%\\.navig\\scripts\\mount-drive.ps1
  Regenerated by ``navig mount sync``; run on login to restore all junctions.
"""

from __future__ import annotations

import json
import platform
import subprocess
import time
from pathlib import Path
from typing import Any

import typer

from navig.core.json_io import JsonReadError, load_json_for_update, load_json_safe
from navig.core.proc_text import console_encoding
from navig.core.yaml_io import atomic_write_text
from navig.platform.paths import config_dir, resolve_user_path, scripts_dir

mount_app = typer.Typer(
    name="mount",
    help="Manage drive junctions (Windows NTFS) via a persistent registry",
    invoke_without_command=True,
    no_args_is_help=False,
)


@mount_app.callback()
def _mount_callback(ctx: typer.Context) -> None:
    if ctx.invoked_subcommand is None:
        import os as _os  # noqa: PLC0415

        if _os.environ.get("NAVIG_LAUNCHER", "fuzzy") == "legacy":
            print(ctx.get_help())
            raise typer.Exit()
        from navig.cli.launcher import smart_launch  # noqa: PLC0415

        smart_launch("mount", mount_app)


# ── Registry path helpers ────────────────────────────────────


def _registry_path() -> Path:
    # `navig_config_dir` does not exist in navig.platform.paths (the function is
    # `config_dir`), so the try always failed and only the fallback ever ran. Use
    # `config_dir()` directly — it is the same thing the fallback used.
    return config_dir() / "registry" / "drives.json"


def _scripts_dir() -> Path:
    return scripts_dir()


# ── Registry I/O ─────────────────────────────────────────────


def _load_registry() -> dict[str, Any]:
    # Read-only view (cmd_list, verify_on_startup): degrade to an empty registry on any
    # failure so a status read never crashes. A read-modify-write MUST use
    # _load_registry_for_update instead, or a transient lock here would return {} and the
    # subsequent _save_registry would wipe every other drive record.
    return load_json_safe(_registry_path(), default={"drives": {}})


def _load_registry_for_update() -> dict[str, Any]:
    """Load the registry for a read-modify-write (add/remove/verify/sync).

    Unlike :func:`_load_registry`, a file that exists-with-content but is transiently
    unreadable (a Windows AV/backup lock) ABORTS the command — otherwise the empty dict it
    would otherwise return, written back by _save_registry, wipes every other mount record.
    """
    try:
        return load_json_for_update(_registry_path(), default={"drives": {}})
    except JsonReadError as exc:
        typer.echo(
            f"✗ The drives registry is temporarily unreadable ({exc}); not modifying it to "
            "avoid wiping your other mounts. Retry in a moment."
        )
        raise typer.Exit(1) from exc


def _save_registry(data: dict[str, Any]) -> None:
    """Persist the registry, retrying the Windows transient lock.

    The replace goes through :func:`atomic_write_text`, which retries ``PermissionError``
    with back-off. The hand-rolled ``os.replace`` this used raised
    ``[WinError 5] Access is denied`` straight out of the command as a traceback whenever
    an antivirus or backup agent held ``drives.json`` for a few milliseconds — measured in
    the full core suite on 2026-09-27 (``test_verify_all_dead``) and reproduced by holding
    a single read handle on the destination. The READ side of this same registry already
    treats a transient lock as its own case (:func:`_load_registry_for_update`); the write
    half is the one where records are lost.

    A lock that outlasts the retries still fails — in words, with exit 1, never a
    traceback and never silently: the caller's read-modify-write did not land.
    ``ensure_ascii=False`` keeps a non-ASCII path in the file readable, as before.
    """
    try:
        atomic_write_text(_registry_path(), json.dumps(data, indent=2, ensure_ascii=False))
    except OSError as exc:
        typer.echo(
            f"✗ Could not write the drives registry ({exc}) — it is held by another "
            "process (antivirus or backup agent). Nothing was changed; retry in a moment."
        )
        raise typer.Exit(1) from exc


# ── Junction helpers ──────────────────────────────────────────


def _is_windows() -> bool:
    return platform.system() == "Windows"


def _create_junction(source: Path, target: Path) -> str | None:
    """
    Create an NTFS junction from *target* → *source*.

    Returns None on success, error string on failure.
    Falls back to symlink on non-Windows for testing.
    """
    if not source.exists():
        return f"Source does not exist: {source}"

    if target.exists() or target.is_symlink():
        if target.is_junction() if hasattr(target, "is_junction") else False:
            return None  # already exists
        return f"Target already exists: {target}"

    target.parent.mkdir(parents=True, exist_ok=True)

    if _is_windows():
        try:
            # Console code page: the CalledProcessError handler below returns
            # `exc.stderr` verbatim as the user-facing error, and cmd.exe's messages are
            # localized. Text mode would also leave `exc.stderr` None under Python's UTF-8
            # mode, turning the error path into an AttributeError inside the handler.
            subprocess.run(
                ["cmd", "/c", "mklink", "/J", str(target), str(source)],
                check=True,
                capture_output=True,
                encoding=console_encoding(),
                errors="replace",
            )
        except subprocess.CalledProcessError as exc:
            return exc.stderr.strip() or str(exc)
    else:
        try:
            target.symlink_to(source.resolve())
        except Exception as exc:
            return str(exc)
    return None


def _remove_junction(target: Path) -> str | None:
    """
    Remove an NTFS junction at *target*.

    Returns None on success, error string on failure.
    """
    if not target.exists() and not target.is_symlink():
        return f"Target does not exist: {target}"

    if _is_windows():
        try:
            subprocess.run(
                ["cmd", "/c", "rmdir", str(target)],
                check=True,
                capture_output=True,
                encoding=console_encoding(),
                errors="replace",
            )
        except subprocess.CalledProcessError as exc:
            return exc.stderr.strip() or str(exc)
    else:
        try:
            if target.is_symlink():
                target.unlink()
            else:
                target.rmdir()
        except Exception as exc:
            return str(exc)
    return None


def _junction_alive(target: Path) -> bool:
    """Return True if junction/symlink at target is accessible."""
    try:
        return target.exists() and target.is_dir()
    except Exception:
        return False


# ── Commands ──────────────────────────────────────────────────


@mount_app.command("add")
def cmd_add(
    label: str = typer.Argument(..., help="Short name for this mount (e.g. 'projects')"),
    source: str = typer.Argument(..., help="Source directory to expose"),
    target: str | None = typer.Argument(
        None, help="Junction target path (default: %USERPROFILE%\\mnt\\<label>)"
    ),
    no_create: bool = typer.Option(
        False, "--no-create", help="Register only; don't create junction"
    ),
) -> None:
    """Register a drive junction and create it immediately."""
    source_path = resolve_user_path(source).expanduser().resolve()
    if not source_path.exists():
        typer.secho(f"Source does not exist: {source_path}", fg=typer.colors.RED)
        raise typer.Exit(1)

    if target:
        target_path = resolve_user_path(target).expanduser().resolve()
    else:
        mnt_root = Path.home() / "mnt"
        target_path = mnt_root / label

    data = _load_registry_for_update()
    drives = data.setdefault("drives", {})

    if label in drives:
        typer.secho(
            f"Label '{label}' already registered → {drives[label]['target']}",
            fg=typer.colors.YELLOW,
        )
        raise typer.Exit(1)

    entry: dict[str, Any] = {
        "label": label,
        "source": str(source_path),
        "target": str(target_path),
        "created_at": time.time(),
        "alive": False,
    }

    if not no_create:
        err = _create_junction(source_path, target_path)
        if err:
            typer.secho(f"Failed to create junction: {err}", fg=typer.colors.RED)
            raise typer.Exit(1)
        entry["alive"] = True
        typer.secho(f"✓ Junction created: {target_path} → {source_path}", fg=typer.colors.GREEN)
    else:
        typer.secho(f"✓ Registered (no junction created): {label}", fg=typer.colors.YELLOW)

    drives[label] = entry
    _save_registry(data)
    typer.echo(f"  Registry: {_registry_path()}")


@mount_app.command("list")
def cmd_list(
    json_output: bool = typer.Option(False, "--json", help="Output raw JSON"),
) -> None:
    """List all registered drive junctions."""
    data = _load_registry()
    drives = data.get("drives", {})

    if not drives:
        typer.echo("No drive junctions registered.")
        return

    if json_output:
        typer.echo(json.dumps(list(drives.values()), indent=2))
        return

    for label, entry in drives.items():
        target = Path(entry["target"])
        alive = _junction_alive(target)
        status_color = typer.colors.GREEN if alive else typer.colors.RED
        status = "✓ alive" if alive else "✗ dead"
        typer.secho(f"  [{status}] {label}", fg=status_color)
        typer.echo(f"     source : {entry['source']}")
        typer.echo(f"     target : {entry['target']}")


@mount_app.command("remove")
def cmd_remove(
    label: str = typer.Argument(..., help="Label of the junction to remove"),
    no_delete: bool = typer.Option(
        False, "--no-delete", help="Remove from registry only; don't delete junction"
    ),
    yes: bool = typer.Option(False, "--yes", "-y", help="Skip confirmation"),
) -> None:
    """Remove a registered drive junction."""
    data = _load_registry_for_update()
    drives = data.get("drives", {})

    if label not in drives:
        typer.secho(f"Label '{label}' not found in registry.", fg=typer.colors.RED)
        raise typer.Exit(1)

    entry = drives[label]
    target_path = Path(entry["target"])

    if not yes:
        typer.confirm(
            f"Remove junction '{label}' ({target_path})?",
            abort=True,
        )

    if not no_delete:
        err = _remove_junction(target_path)
        if err:
            typer.secho(f"Warning: could not remove junction: {err}", fg=typer.colors.YELLOW)
        else:
            typer.secho(f"✓ Junction removed: {target_path}", fg=typer.colors.GREEN)

    del drives[label]
    _save_registry(data)
    typer.echo(f"  Removed '{label}' from registry.")


@mount_app.command("verify")
def cmd_verify(
    json_output: bool = typer.Option(False, "--json", help="Output raw JSON"),
) -> None:
    """Verify all registered junctions are alive and update registry status."""
    data = _load_registry_for_update()
    drives = data.get("drives", {})

    if not drives:
        if json_output:
            typer.echo("[]")
        else:
            typer.echo("No drive junctions to verify.")
        return

    dead: list[str] = []
    results = []

    for label, entry in drives.items():
        target = Path(entry["target"])
        alive = _junction_alive(target)
        entry["alive"] = alive
        results.append({"label": label, "alive": alive, "target": entry["target"]})
        if not alive:
            dead.append(label)

    _save_registry(data)

    if json_output:
        typer.echo(json.dumps(results, indent=2))
        return

    for r in results:
        color = typer.colors.GREEN if r["alive"] else typer.colors.RED
        icon = "✓" if r["alive"] else "✗"
        typer.secho(f"  {icon} {r['label']}: {r['target']}", fg=color)

    if dead:
        typer.secho(f"\n{len(dead)} dead junction(s): {', '.join(dead)}", fg=typer.colors.YELLOW)
    else:
        typer.secho(f"\nAll {len(results)} junction(s) alive.", fg=typer.colors.GREEN)


@mount_app.command("sync")
def cmd_sync(
    dry_run: bool = typer.Option(False, "--dry-run", help="Preview without changes"),
) -> None:
    """
    Verify all junctions and regenerate mount-drive.ps1 helper script.

    Run mount-drive.ps1 on Windows login or after reboot to restore
    all junctions automatically.
    """
    # First verify
    typer.echo("Verifying junctions…")
    # Run verify inline (without invoking subprocess)
    data = _load_registry_for_update()
    drives = data.get("drives", {})
    dead: list[str] = []

    for label, entry in drives.items():
        target = Path(entry["target"])
        alive = _junction_alive(target)
        entry["alive"] = alive
        if not alive:
            dead.append(label)

    if not dry_run:
        _save_registry(data)

    for label in dead:
        typer.secho(f"  ✗ dead: {label}", fg=typer.colors.YELLOW)

    # Regenerate script
    script_path = _scripts_dir() / "mount-drive.ps1"
    script_content = _generate_ps1(drives)

    if dry_run:
        typer.echo(f"\nWould write: {script_path}")
        typer.echo("--- Script preview ---")
        typer.echo(script_content[:1000])
        return

    script_path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(script_path, script_content)
    typer.secho(f"\n✓ Script written: {script_path}", fg=typer.colors.GREEN)

    if dead:
        typer.secho(
            f"\nWarning: {len(dead)} dead junction(s). Run 'navig mount verify' to see details.",
            fg=typer.colors.YELLOW,
        )
    else:
        typer.secho(f"All {len(drives)} junction(s) healthy.", fg=typer.colors.GREEN)


# ── Script generator ──────────────────────────────────────────


def _generate_ps1(drives: dict[str, Any]) -> str:
    lines = [
        "# Auto-generated by `navig mount sync`",
        "# Run on login to restore NTFS junctions.",
        "# DO NOT EDIT — regenerate with: navig mount sync",
        "",
        "$ErrorActionPreference = 'Continue'",
        "",
    ]
    if not drives:
        lines.append("# No junctions registered.")
        return "\n".join(lines) + "\n"

    for label, entry in drives.items():
        source = entry["source"].replace("\\", "\\\\")
        target = entry["target"].replace("\\", "\\\\")
        lines += [
            f"# --- {label} ---",
            f'if (-not (Test-Path "{target}")) {{',
            f'    Write-Host "Creating junction: {label}"',
            f'    cmd /c mklink /J "{target}" "{source}"',
            "} else {",
            f'    Write-Host "Junction already exists: {label}"',
            "}",
            "",
        ]

    lines += [
        'Write-Host "Done. Run: navig mount verify"',
    ]
    return "\n".join(lines) + "\n"


# ── Daemon bootstrap helper ───────────────────────────────────


def verify_on_startup() -> list[str]:
    """
    Verify all registered junctions and report the dead ones.

    Returns a list of dead labels (empty if all healthy).

    NOT WIRED, and the docstring used to say otherwise: this opened with "Called by the
    daemon on startup", which was a claim — `verify_on_startup` appears nowhere outside
    this module and its tests. Wiring it is a product decision; keeping it daemon-SAFE is
    not. The write-back is therefore contained here, because the `alive` flags are a CACHE
    (`_junction_alive` recomputes every one of them above), so a registry held by an
    antivirus agent costs the refresh and never the answer — and because `_save_registry`
    reports a persistent lock with `typer.Exit`, which belongs to a CLI verb and has no
    meaning inside a daemon.
    """
    data = _load_registry()
    drives = data.get("drives", {})
    dead = []
    changed = False

    for label, entry in drives.items():
        alive = _junction_alive(Path(entry["target"]))
        if entry.get("alive") != alive:
            entry["alive"] = alive
            changed = True
        if not alive:
            dead.append(label)

    if changed:
        try:
            _save_registry(data)
        except (OSError, typer.Exit) as exc:
            # Best-effort, but never silent: a discarded write with no trace is how
            # "the registry never updates" becomes unexplainable. typer.Exit is a
            # RuntimeError, not an OSError, so it needs naming separately.
            from navig.core.logging import get_logger  # noqa: PLC0415

            get_logger("mount").warning(
                f"could not refresh junction health in the drives registry: {exc}"
            )

    return dead
